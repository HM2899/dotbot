function descendants(pid) {
  const rows = execFileSync('ps', ['-eo', 'pid=,ppid=']).toString().trim().split('\n').map(line => line.trim().split(/\s+/).map(Number))
  const ids = new Set([pid]); let previous
  do { previous = ids.size; for (const [id, parent] of rows) if (ids.has(parent)) ids.add(id) } while (ids.size !== previous)
  return [...ids]
}
