#!/usr/bin/env node
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { startServer, until } from './harness.mjs'
import { startTelegram, startWeChat } from './fake-social.mjs'
let app, platform, wechat
try {
  platform = await startTelegram(); app = await startServer()
  const { call } = app
  const chief = (await call('team.state')).bots[0]
  const token = '123:private-channel-token'
  const params = { kind: 'telegram', name: 'Local Telegram', target: chief.conversation, settings: { token, apiBase: platform.base }, allow: [] }
  const id = await call('channel.save', params)
  const channel = async () => (await call('team.state')).channels.find(c => c.id === id)
  const messages = async () => (await call('chat.page', { conversation: chief.conversation })).items
  await until('online', async () => (await channel()).status.state === 'online')
  assert.equal((await channel()).settings.token, '••••••')
  platform.files.set('private-file', { name: 'private.txt', bytes: Buffer.from('must not download') })
  platform.push('unauthorized hello', { document: { file_id: 'private-file', file_name: 'private.txt' } })
  await until('pending sender', async () => (await channel()).status.pending.some(p => p.id === '42'))
  assert.ok(!(await messages()).some(m => m.kind === 'user' && m.text === 'unauthorized hello'))
  assert.equal(platform.downloaded.length, 0)
  await call('channel.allow', { id, sender: '42', allow: true })
  const accepted = platform.push('hello from platform')
  await until('reply sent', () => platform.sent.some(m => m.text.includes('hello from platform')))
  assert.ok((await channel()).status.lastReceived)
  await until('send receipt', async () => (await channel()).status.lastSent)
  const firstTrace=await until('correlated delivery trace',async()=>{const d=await call('channel.diagnostics',{id});return d.samples===1&&d.traces[0]})
  assert.equal(firstTrace.status,'sent');for(const key of ['attachmentMs','queueMs','modelMs','deliveryQueueMs','sendMs','totalMs'])assert.ok(firstTrace[key]>=0)
  assert.ok(!JSON.stringify(await call('channel.diagnostics',{id})).includes('hello from platform'))
  platform.updates.push(accepted)
  platform.push('/stop@AnotherBot', { group: true })
  platform.push('/new', { group: true })
  platform.push('hello @TestBotExtra', { group: true })
  platform.push('hello @TESTBOT', { group: true })
  await until('group reply', () => platform.sent.some(m => m.chat_id === -100 && m.text.includes('hello')))
  assert.equal((await messages()).filter(m => m.kind === 'user' && m.text === 'hello from platform').length, 1)
  assert.ok(!(await messages()).some(m => /AnotherBot|TestBotExtra/.test(m.text)))
  assert.equal((await call('channel.diagnostics',{id})).traces.length,2,'duplicate updates must not create duplicate diagnostic traces')
  console.log('ok   Telegram authorization, group mentions, duplicate updates and reply receipts work')
  const pdfBytes = Buffer.from('%PDF-1.4\nfixture\n%%EOF')
  platform.files.set('incoming-pdf', { name: 'incoming.pdf', bytes: pdfBytes })
  platform.push('REPORT_ATTACHMENT anything', { document: { file_id: 'incoming-pdf', file_name: 'incoming.pdf', file_size: pdfBytes.length } })
  await until('Telegram PDF reaches model', () => platform.sent.some(m => m.text.includes('Attachments: images=0 pdf=1')))
  assert.ok((await messages()).some(m => m.kind === 'user' && m.files?.some(f => f.name === 'incoming.pdf')))
  assert.ok(platform.downloaded.includes('incoming-pdf'))
  platform.push(`FAIL private failure ${token}`)
  await until('model failure returned to Telegram', () => platform.sent.some(m => m.text.includes('任务执行失败') && m.text.includes('private failure')))
  assert.ok(!platform.sent.some(m => m.text.includes(token)))
  await call('settings.local-computer', { enabled: true })
  const output = join(app.home, 'work/platform-result.txt'), fileBytes = Buffer.from('social file delivery verified')
  mkdirSync(join(app.home, 'work'), { recursive: true }); writeFileSync(output, fileBytes)
  const approveAndWait = async (what, check) => until(what, async () => {
    for (const approval of (await call('team.state')).work.approvals) await call('approval.answer', { id: approval.id, allow: true })
    return check()
  })
  platform.push(`TOOL local_send_file ${JSON.stringify({ path: output })}`)
  await approveAndWait('generated Telegram document', () => platform.documents.some(m => m.files[0]?.filename === 'platform-result.txt'))
  assert.deepEqual(platform.documents[0].files[0].bytes, fileBytes)
  const worker = await call('bot.create', { name: 'Social file worker', role: 'File delivery' })
  const documentsBefore = platform.documents.length
  platform.push(`TOOL message_bot ${JSON.stringify({ bot: worker.name, text: `TOOL local_send_file ${JSON.stringify({ path: output })}` })}`)
  await approveAndWait('delegated file returns to Telegram', () => platform.documents.length > documentsBefore)
  assert.deepEqual(platform.documents.at(-1).files[0].bytes, fileBytes)
  platform.push('DELAY 1800')
  await until('social task running', async () => (await call('team.state')).work.runs[chief.conversation])
  platform.push('/stop')
  await until('cancellation returned', () => platform.sent.some(m => m.text.includes('任务已停止')))
  console.log('ok   Telegram downloads authorized files, returns native PDFs, reports failures/cancellation and sends direct/delegated artifacts')


  const oldCursor = JSON.parse(readFileSync(join(app.home, 'team/channels.json')))[0].settings.cursor
  assert.ok(Number(oldCursor) > 0)
  const before = (await messages()).filter(m => m.kind === 'user').length
  await call('channel.reconnect', { id })
  await until('cursor reused', () => platform.offsets.slice(-2).some(n => n >= Number(oldCursor)))
  assert.equal((await messages()).filter(m => m.kind === 'user').length, before)
  await call('channel.save', { ...params, id, settings: { token: '••••••', apiBase: platform.base }, allow: ['42'], enabled: false })
  assert.equal((await channel()).status.state, 'off')
  await assert.rejects(call('channel.reconnect', { id }), /Resume/)
  platform.push('while paused')
  await new Promise(resolve => setTimeout(resolve, 180))
  assert.equal((await messages()).filter(m => m.kind === 'user').length, before)
  assert.equal(JSON.parse(readFileSync(join(app.home, 'team/channels.json')))[0].settings.token, token)
  console.log('ok   reconnect resumes from the saved cursor; pause stops delivery and masked edits keep credentials')

  platform.failSend(`Forbidden: ${token}`)
  await call('channel.save', { ...params, id, settings: { token: '••••••', apiBase: platform.base }, allow: ['42'], enabled: true })
  await until('delivery failure visible', async () => (await channel()).status.lastError)
  assert.ok(!(JSON.stringify(await channel())).includes(token))
  assert.match((await channel()).status.lastError, /Forbidden/)
  platform.failSend('')
  platform.push('recover delivery')
  await until('delivery recovered', () => platform.sent.some(m => m.text.includes('recover delivery')))
  await until('error cleared', async () => !(await channel()).status.lastError)
  await call('channel.allow', { id, sender: '42', allow: false })
  platform.push('access revoked')
  await until('sender pending again', async () => (await channel()).status.pending.some(p => p.id === '42'))
  assert.ok(!(await messages()).some(m => m.kind === 'user' && m.text === 'access revoked'))
  platform.failPoll(`Bad token: ${token}`)
  await call('channel.reconnect', { id })
  await until('connection error visible', async () => (await channel()).status.state === 'error')
  assert.ok(!JSON.stringify(await channel()).includes(token))
  await call('channel.delete', { id })
  assert.ok(!(await call('team.state')).channels.some(c => c.id === id))
  console.log('ok   delivery failures are visible and redacted; recovery, access revocation and deletion work')
  wechat = await startWeChat()
  const wxParams = { kind: 'wechat', name: 'Local WeChat', target: chief.conversation, settings: { baseUrl: wechat.base, cdnBase: `${wechat.base}/cdn` }, allow: [] }
  const wxId = await call('channel.save', wxParams)
  const wx = async () => (await call('team.state')).channels.find(c => c.id === wxId)
  await call('channel.login', { id: wxId })
  await until('QR displayed', async () => (await wx()).status.qr)
  wechat.setStatus('scaned')
  await until('scan confirmation displayed', async () => (await wx()).status.detail.includes('confirm on the phone'))
  await call('channel.save', { ...wxParams, id: wxId, settings: {}, enabled: false })
  wechat.setStatus('confirmed')
  await new Promise(resolve => setTimeout(resolve, 180))
  assert.equal((await wx()).status.state, 'off')
  assert.ok(!(await wx()).status.qr)
  assert.ok(!JSON.parse(readFileSync(join(app.home, 'team/channels.json')))[0].settings.token)
  await assert.rejects(call('channel.login', { id: wxId }), /Resume/)
  await call('channel.save', { ...wxParams, id: wxId, settings: {}, enabled: true })
  await call('channel.login', { id: wxId })
  await until('WeChat signed in', async () => (await wx()).status.state === 'online')
  assert.equal((await wx()).settings.token, '••••••')
  assert.ok((await wx()).allow.includes('wx-user-42'))
  wechat.push('REPORT_ATTACHMENT anything', { files: [{ name: 'wechat.pdf', bytes: pdfBytes }] })
  await until('WeChat decrypted PDF reaches model', () => wechat.sent.some(m => m.item_list.some(i => i.text_item?.text.includes('Attachments: images=0 pdf=1'))))
  assert.ok(wechat.downloads.length)
  wechat.push(`FAIL WeChat synthetic failure`)
  await until('WeChat execution failure returned', () => wechat.sent.some(m => m.item_list.some(i => i.text_item?.text.includes('任务执行失败'))))
  wechat.push(`TOOL local_send_file ${JSON.stringify({ path: output })}`)
  await approveAndWait('WeChat encrypted file uploaded', () => wechat.uploaded.length > 0)
  await until('WeChat file message delivered', () => wechat.sent.some(m => m.item_list.some(i => i.file_item?.file_name === 'platform-result.txt')))
  assert.deepEqual(wechat.uploaded[0].bytes, fileBytes)
  assert.equal(wechat.uploaded[0].rawfilemd5, wechat.uploaded[0].digest)
  console.log('ok   WeChat downloads/decrypts attachments, returns failures and uploads/encrypts deliverable files')

  wechat.push('DELAY 350\n微信延迟分段诊断')
  await until('WeChat delayed reply delivered',()=>wechat.sent.some(m=>m.item_list.some(i=>i.text_item?.text.includes('微信延迟分段诊断'))))
  const diagnostic=await until('WeChat latency attribution',async()=>{const d=await call('channel.diagnostics',{id:wxId});return d.traces.find(t=>t.status==='sent'&&t.modelMs>=300)&&d})
  assert.ok(diagnostic.p95Ms>=diagnostic.p50Ms);assert.ok(!JSON.stringify(diagnostic).includes('wx-user-42'))
  console.log('ok   WeChat diagnostic traces correlate delivery and execution latency without storing message content or sender identity')

  await call('bot.create',{name:'平台核对员',role:'Review'})
  await call('bot.create',{name:'平台整理员',role:'Write'})
  wechat.push('整理资料 AUTO_WORKFLOW social_dag')
  const progressTrace=await until('WeChat workflow progress is distinguished from final delivery',async()=>{const d=await call('channel.diagnostics',{id:wxId});return d.traces.find(t=>t.status==='progress_sent')})
  assert.equal(progressTrace.totalMs,null)
  await until('WeChat workflow unified final delivery',()=>wechat.sent.some(m=>m.item_list.some(i=>i.text_item?.text.includes('Unified: social_dag'))))
  await until('WeChat workflow final timing completed',async()=>(await call('channel.diagnostics',{id:wxId})).traces.find(t=>t.id===progressTrace.id)?.status==='sent')
  console.log('ok   intermediate collaboration replies do not count as final delivery latency samples')

  await until('WeChat timeout hint consumed', () => wechat.updatePolls.length >= 2)
  wechat.hangNextPoll()
  await until('WeChat idle long poll pending', () => wechat.hungPolls() === 1)
  const receiveStarted = Date.now()
  const timeoutMessage = wechat.push('微信空闲轮询超时后的消息')
  const timeoutCursor = `wx-${Number(timeoutMessage.message_id.split('-').at(-1)) + 1}`
  await until('WeChat receives after idle timeout without exponential reconnect delay', async () => (await messages()).some(m => m.kind === 'user' && m.text === '微信空闲轮询超时后的消息'), 8500)
  assert.ok(Date.now() - receiveStarted < 8500)
  assert.equal((await wx()).status.state, 'online')
  await until('WeChat cursor saved after accepted input', () => JSON.parse(readFileSync(join(app.home, 'team/channels.json')))[0].settings.cursor === timeoutCursor)
  const savedWxCursor = JSON.parse(readFileSync(join(app.home, 'team/channels.json')))[0].settings.cursor
  const pollsBeforeFailure = wechat.updatePolls.length
  wechat.failNextPoll()
  await until('WeChat network error shown', async () => (await wx()).status.state === 'error')
  const reconnectMessage = wechat.push('微信网络恢复后的消息')
  const reconnectCursor = `wx-${Number(reconnectMessage.message_id.split('-').at(-1)) + 1}`
  await until('WeChat network reconnect receives promptly', async () => (await messages()).some(m => m.kind === 'user' && m.text === '微信网络恢复后的消息'), 4000)
  assert.ok(wechat.updatePolls.slice(pollsBeforeFailure).every(p => p.cursor === savedWxCursor || p.cursor === reconnectCursor))
  assert.equal((await messages()).filter(m => m.kind === 'user' && m.text === '微信空闲轮询超时后的消息').length, 1)
  console.log('ok   WeChat follows provider long-poll deadlines, renews quiet polls without backoff and reconnects using the latest cursor without duplicate input')

  await call('channel.save', { ...wxParams, id: wxId, name: 'Renamed WeChat', settings: {}, allow: ['wx-user-42'] })
  const wxStored = JSON.parse(readFileSync(join(app.home, 'team/channels.json')))[0]
  assert.equal(wxStored.settings.baseUrl, wechat.base)
  assert.equal(wxStored.settings.token, 'private-wechat-fixture-token')
  wechat.setStatus('wait')
  await call('channel.login', { id: wxId })
  await call('channel.delete', { id: wxId })
  const polls = wechat.polls()
  await new Promise(resolve => setTimeout(resolve, 180))
  assert.equal(wechat.polls(), polls)
  console.log('ok   WeChat QR confirmation, pause cancellation, secret preservation and login deletion work')
} finally {
  await app?.stop(); await platform?.stop(); await wechat?.stop()
  console.log('ok   isolated channel service and mock platform cleaned up')
}
