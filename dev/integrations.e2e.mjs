#!/usr/bin/env node
import assert from 'node:assert/strict'
import { mkdtempSync, rmSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { startServer, until } from './harness.mjs'
import { startAccounts } from './fake-accounts.mjs'
import { startTelegram } from './fake-social.mjs'
const directory = mkdtempSync(join(tmpdir(), 'dotbot-integrations-'))
let app, accounts, telegram
try {
  accounts = await startAccounts(); telegram = await startTelegram()
  app = await startServer({ directory, keepHome: true })
  let call = (...args) => app.call(...args)
  const chief = (await call('team.state')).bots[0], conversation = chief.conversation
  const idle = () => until('conversation idle', async () => !(await call('team.state')).work.runs[conversation])
  const messages = () => call('chat.page', { conversation }).then(p => p.items)
  async function authorize(account) {
    const start = await call('account.authorize', { id: account.id })
    const auth = new URL(start.url)
    assert.equal(auth.searchParams.get('code_challenge_method'), 'S256')
    assert.ok(!start.url.includes('fixture-client-private'))
    await fetch(start.url)
    assert.equal((await call('team.state')).accounts.find(a => a.id === account.id).status, 'connected')
    // State is single use; replay cannot replace the account grant.
    await fetch(`${app.base}/oauth/callback?${new URLSearchParams({ state: auth.searchParams.get('state'), code: 'replayed' })}`)
    assert.equal((await call('team.state')).accounts.find(a => a.id === account.id).status, 'connected')
  }
  const params = { provider: 'github', name: 'Fixture GitHub', clientId: 'fixture-client', clientSecret: 'fixture-client-private', scopes: ['read:user', 'repo', 'admin:repo_hook'], writable: true, endpoints: accounts.endpoints }
  const account = await call('account.save', params)
  assert.equal(account.status, 'disconnected')
  assert.ok(!JSON.stringify(account).includes('fixture-client-private'))
  await assert.rejects(call('account.save', { ...params, scopes: ['arbitrary-scope'] }), /permissions/)
  await assert.rejects(call('account.save', { ...params, endpoints: { ...accounts.endpoints, token: 'http://example.com/token' } }), /HTTPS/)
  await authorize(account)
  assert.equal((await call('account.test', { id: account.id })).identity, 'fixture-user')
  assert.equal(accounts.refreshes(), 1)
  await call('account.test', { id: account.id }); assert.equal(accounts.refreshes(), 1)
  assert.equal(statSync(join(directory, 'team/accounts.json')).mode & 0o777, 0o600)
  assert.ok(!JSON.stringify(await call('team.state')).includes('fixture-access-secret'))
  await call('chat.send', { conversation, text: `TOOL account_request ${JSON.stringify({ account: account.id, path: '/user' })}` })
  await until('authorized API tool result', async () => (await messages()).some(i => i.kind === 'bot' && i.text.includes('fixture-user')))
  assert.ok(!JSON.stringify(await messages()).includes('fixture-access-secret'))
  await idle()
  accounts.failIdentity(true)
  await assert.rejects(call('account.test', { id: account.id }), /HTTP 403/)
  assert.equal((await call('team.state')).accounts[0].status, 'error')
  accounts.failIdentity(false); await call('account.test', { id: account.id })
  await call('bot.update', { id: chief.id, permission: 'readonly' })
  const writeCount = accounts.requests.filter(r => r.path === '/api/write').length
  await call('chat.send', { conversation, text: `TOOL account_request ${JSON.stringify({ account: account.id, method: 'POST', path: '/write', body: { hello: 'world' } })}` })
  await idle(); assert.equal(accounts.requests.filter(r => r.path === '/api/write').length, writeCount)
  await call('bot.update', { id: chief.id, permission: 'ask' })
  await call('chat.send', { conversation, text: `TOOL account_request ${JSON.stringify({ account: account.id, method: 'POST', path: '/write', body: { hello: 'world' } })}` })
  const accountApproval = await until('account write approval', async () => (await call('team.state')).work.approvals.find(a => a.tool === 'account_request'))
  await call('approval.answer', { id: accountApproval.id, allow: false }); await idle()
  assert.equal(accounts.requests.filter(r => r.path === '/api/write').length, writeCount)
  await call('bot.update', { id: chief.id, permission: 'auto' })
  console.log('ok   OAuth uses single-use state and verified PKCE; refresh, credential privacy, real API tests and visible failure state work')

  await call('secret.set', { name: 'MCP_FIXTURE', value: 'fixture-mcp-private' })
  await call('connection.save', { name: 'fixture-mcp', kind: 'http', url: `${accounts.base}/mcp`, headers: { Authorization: 'Bearer ${MCP_FIXTURE}' } })
  const check = await call('connection.test', { name: 'fixture-mcp' })
  assert.equal(check.state, 'connected'); assert.deepEqual(check.tools, ['fixture_read']); assert.equal(accounts.sessions.size, 0)
  const stdio = join(directory, 'probe.mjs')
  writeFileSync(stdio, `import readline from 'node:readline';for await(const line of readline.createInterface({input:process.stdin})){const r=JSON.parse(line);if(r.id)console.log(JSON.stringify({jsonrpc:'2.0',id:r.id,result:r.method==='initialize'?{serverInfo:{name:'fixture',version:'1'}}:{tools:[{name:'stdio_read'}]}}))}`)
  await call('connection.save', { name: 'fixture-stdio', kind: 'stdio', command: process.execPath, args: [stdio] })
  assert.deepEqual((await call('connection.test', { name: 'fixture-stdio' })).tools, ['stdio_read'])
  await call('connection.save', { name: 'bad-mcp', kind: 'http', url: `${accounts.base}/missing` })
  assert.equal((await call('connection.test', { name: 'bad-mcp' })).state, 'error')
  console.log('ok   connection tests initialize real HTTP/SSE and stdio MCP sessions, list tools and close their sessions/processes')

  await call('secret.set', { name: 'WEBHOOK_SIGNING', value: 'webhook-private-signing' })
  const routine = await call('routine.create', { title: 'Webhook fixture', target: conversation, prompt: 'Handle verified push', when: { kind: 'event', source: 'github', event: 'push', filters: { '/ref': 'refs/heads/main' }, signingSecret: 'WEBHOOK_SIGNING' } })
  const beforeLocal = (await messages()).length
  const local = await call('event.test', { id: routine.id, payload: { ref: 'refs/heads/main' } })
  assert.equal(local.local, true); assert.equal(local.matched, true); assert.equal(local.accepted, false)
  assert.equal((await messages()).length, beforeLocal)
  let setup = await call('event.setup', { id: routine.id }); assert.ok(setup.status.localTest); assert.ok(!setup.status.received)
  setup = await call('event.register', { id: routine.id, account: account.id, repository: 'owner/repo' })
  assert.ok(setup.status.registered); assert.ok(!setup.status.received); assert.equal(accounts.hooks.length, 1)
  await call('event.register', { id: routine.id, account: account.id, repository: 'owner/repo' }); assert.equal(accounts.hooks.length, 1)
  await call('event.provider-test', { id: routine.id })
  setup = await call('event.setup', { id: routine.id }); assert.ok(setup.status.received); assert.equal(setup.status.matched, false)
  assert.equal((await call('event.subscription', { id: routine.id })).status.providerUrlMatches, true)
  assert.equal((await messages()).length, beforeLocal)
  await fetch(setup.webhook, { method: 'POST', body: '{}', headers: { 'x-hub-signature-256': 'sha256=invalid' } })
  assert.ok((await call('event.setup', { id: routine.id })).status.error)
  await call('event.subscription', { id: routine.id, delete: true }); assert.equal(accounts.hooks.length, 0)
  console.log('ok   signed local tests do not dispatch model work or impersonate platform arrival; GitHub hook registration is reusable and provider ping proves arrival')

  await call('settings.local-computer', { enabled: true })
  await call('bot.update', { id: chief.id, permission: 'ask' })
  const marker = join(directory, 'external-step.txt')
  const queuedPdfResponse = await fetch(`${app.base}/api/files?${new URLSearchParams({ conversation, name: 'queued.pdf' })}`, { method: 'POST', headers: { cookie: app.cookie }, body: '%PDF-1.4\nqueued fixture\n%%EOF' })
  const queuedPdf = (await queuedPdfResponse.json()).file
  await call('chat.send', { conversation, text: `TOOL task_checkpoint {"summary":"Step 1 is ready; verify the external marker before continuing."}\nTOOL local_run ${JSON.stringify({ command: `printf verified >> '${marker}'`, timeout_s: 5 })}\nWAIT_AFTER_TOOLS 10000` })
  const approval = await until('local action approval', async () => (await call('team.state')).work.approvals.find(a => a.tool === 'local_run'))
  await call('approval.answer', { id: approval.id, allow: true })
  const pending = await until('saved checkpoint and confirmed side effect', async () => (await call('recovery.list')).find(w => w.status === 'running' && w.checkpoint.includes('Step 1') && w.actions.some(a => a.tool === 'local_run' && a.state === 'confirmed')))
  assert.equal(readFileSync(marker, 'utf8'), 'verified')
  await app.stop()
  const recoveryPath = join(directory, 'team/recovery.json'), receipts = JSON.parse(readFileSync(recoveryPath))
  receipts.push({ ...receipts.find(w => w.id === pending.id), id: 'work-queued-native-input', text: 'REPORT_ATTACHMENT queued-native-input', status: 'queued', task: null, routine: null, routes: [], files: [queuedPdf], actions: [], checkpoint: '', result: null })
  writeFileSync(recoveryPath, JSON.stringify(receipts))
  app = await startServer({ directory, keepHome: true })
  const queuedInput=await call('recovery.get',{id:'work-queued-native-input'})
  assert.equal(queuedInput.status,'failed','unfinished ordinary requests must not replay side effects automatically')
  const interrupted=await call('recovery.get',{id:pending.id})
  assert.equal(interrupted.status,'failed');assert.ok(interrupted.checkpoint.includes('Step 1'))
  assert.ok(interrupted.actions.some(a=>a.tool==='local_run'&&a.state==='confirmed'))
  assert.equal(readFileSync(marker,'utf8'),'verified')
  await call('chat.send',{conversation,text:'REPORT_ATTACHMENT queued-native-input',files:[queuedPdf.src]})
  await until('deliberately resent native input restored',async()=>(await messages()).some(m=>m.kind==='bot'&&m.text==='Attachments: images=0 pdf=1; text=false'))
  assert.equal(readFileSync(marker,'utf8'),'verified')
  console.log('ok   restart retains ordinary request attachments, checkpoints and action evidence without replaying external actions; deliberate resubmission restores native input')

  const helper=await call('bot.create',{name:'RecoveryHelper',role:'Checks durable returns',instructions:'Return a short answer.'})
  await idle()
  await call('chat.send',{conversation,text:'TOOL message_bot {"bot":"RecoveryHelper","text":"durable-return-marker"}'})
  const flow=await until('manual workflow final delivery',async()=>(await call('workflow.list')).find(w=>w.source===conversation&&w.status==='completed'))
  const child=(await call('task.list')).find(t=>t.workflow===flow.id&&t.target===helper.id)
  assert.ok(child);assert.equal(child.attempt,1)
  const returnKey=`${flow.id}:${flow.attempt}`
  const returns=JSON.parse(readFileSync(recoveryPath)).filter(w=>w.replyFor===returnKey)
  assert.equal(returns.length,1);assert.equal(returns[0].status,'completed')
  await idle();await app.stop()
  const workflowPath=join(directory,'team/workflows.json'),saved=JSON.parse(readFileSync(workflowPath))
  saved.find(w=>w.id===flow.id).status='delivering';writeFileSync(workflowPath,JSON.stringify(saved))
  app=await startServer({directory,keepHome:true})
  await until('persisted manual delivery reconciled',async()=>(await call('workflow.list')).find(w=>w.id===flow.id)?.status==='completed')
  assert.deepEqual(JSON.parse(readFileSync(recoveryPath)).filter(w=>w.replyFor===returnKey).map(w=>w.id),returns.map(w=>w.id))
  assert.equal((await call('task.get',{id:child.id})).attempt,1)
  console.log('ok   manual delegation participates in one durable workflow summary; restart reconciles its delivery without repeating the child or summary')

  const channelId = await call('channel.save', { kind: 'telegram', target: conversation, settings: { token: 'fixture-bot-token', apiBase: telegram.base }, allow: ['42'] })
  telegram.failSend('fixture send rejected')
  telegram.push('durable reply')
  const failed = await until('durable send failure', async () => (await call('delivery.list')).find(d => d.channel === channelId && d.status === 'failed'))
  const sentBefore = telegram.sent.length
  await app.stop()
  const outboxPath = join(directory, 'team/outbox.json'), rows = JSON.parse(readFileSync(outboxPath))
  const row = rows.find(d => d.id === failed.id)
  row.parts = [{ kind: 'text', value: 'confirmed-first-part' }, { kind: 'text', value: 'uncertain-middle-part' }, { kind: 'text', value: 'remaining-last-part' }]; row.cursor = 1; row.status = 'sending'
  rows.push({ ...row, id: 'delivery-queued-before-restart', cursor: 0, status: 'queued', parts: [{ kind: 'text', value: 'queued-before-restart' }], route: { ...row.route, data: { ...row.route.data, replyTo: 999 } } })
  writeFileSync(outboxPath, JSON.stringify(rows))
  telegram.failSend(''); app = await startServer({ directory, keepHome: true })
  await until('queued delivery restored', () => telegram.sent.some(m => m.text === 'queued-before-restart'))
  assert.equal((await call('delivery.list')).find(d => d.id === failed.id).status, 'uncertain')
  await assert.rejects(call('delivery.retry', { id: failed.id }), /Check whether/)
  await call('delivery.retry', { id: failed.id, reviewed: true, skip: true })
  await until('remaining delivery resumed', () => telegram.sent.some(m => m.text === 'remaining-last-part'))
  assert.ok(!telegram.sent.slice(sentBefore).some(m => ['confirmed-first-part', 'uncertain-middle-part'].includes(m.text)))
  assert.equal((await call('delivery.list')).find(d => d.id === failed.id).sent, 3)
  const finalCount = telegram.sent.length
  await app.stop(); app = await startServer({ directory, keepHome: true })
  await new Promise(resolve => setTimeout(resolve, 250))
  assert.equal(telegram.sent.length, finalCount)
  console.log('ok   queued replies survive restart; in-flight sends require review, confirmed parts are not replayed, skip resumes remaining parts and delivered replies stay deduplicated')

  const revoked = await call('account.revoke', { id: account.id })
  assert.equal(revoked.localRevoked, true); assert.equal(accounts.revocations(), 1)
  await assert.rejects(call('account.test', { id: account.id }), /Authorize/)
  assert.ok(!readFileSync(join(directory, 'team/accounts.json'), 'utf8').includes('fixture-refresh-secret'))
  console.log('ok   provider revocation clears local credentials and prevents subsequent API access')
} finally {
  await app?.stop(); await accounts?.stop(); await telegram?.stop(); rmSync(directory, { recursive: true, force: true })
  console.log('ok   all OAuth/MCP/platform fixtures and restarted services cleaned up')
}
