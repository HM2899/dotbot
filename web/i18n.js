// key with {slots}; the slots carry over into the translation.
let TEMPLATES = null
function fromTemplate(text) {
  TEMPLATES ??= Object.keys(ZH).filter(k => k.includes('{')).map(k => {
    const names = [...k.matchAll(/\{(\w+)\}/g)].map(m => m[1])
    const source = k.split(/\{\w+\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('([\\s\\S]+?)')
    return { re: new RegExp(`^${source}$`), names, to: ZH[k], fixed: k.replace(/\{\w+\}/g, '').length }
  }).sort((a, b) => b.fixed - a.fixed) // the most specific key wins: "No Bot named {name}. Call list_bots." before "No Bot named {name}"
  for (const { re, names, to } of TEMPLATES) {
    const m = String(text ?? '').match(re)
    if (m) return to.replace(/\{(\w+)\}/g, (slot, key) => { if (!names.includes(key)) return slot; const part = m[names.indexOf(key) + 1]; return ZH[part] ?? part })
  }
  return null
}
