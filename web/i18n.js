// The fixed text in index.html, marked with data-i18n (text), data-i18n-title and data-i18n-placeholder.
function translateStatic() {
  document.documentElement.lang = LANG === 'zh' ? 'zh-CN' : 'en'
  // Elements app.js has since filled with markup (icon buttons, menu rows) relabel themselves;
  // overwriting their text would drop the icon, and its render cache would not restore it.
  for (const el of document.querySelectorAll('[data-i18n]')) if (!el.childElementCount) el.textContent = t(el.dataset.i18n)
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle)
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder)
  for (const el of document.querySelectorAll('[data-i18n-aria-label]')) el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel))
  const toggle = document.querySelector('#toggle-lang')
  if (toggle) toggle.textContent = LANG === 'zh' ? 'EN' : '中文'
}
