let LANG = (() => {
  const saved = localStorage.getItem('dotbot.lang')
  if (saved === 'zh' || saved === 'en') return saved
  return /^zh\b/i.test(navigator.language ?? '') ? 'zh' : 'en'
})()

function t(text, vars) {
  const template = (LANG === 'zh' && ZH[text]) || text
  if (LANG === 'zh' && !ZH[text] && !vars) return fromTemplate(text) ?? text
  return vars ? template.replace(/\{(\w+)\}/g, (slot, key) => (key in vars ? String(vars[key]) : slot)) : template
}
